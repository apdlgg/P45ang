function parseScalar(v) {
  v = v.trim();
  if ((v.startsWith('"') && v.endsWith('"') && v.length > 1) || (v.startsWith("'") && v.endsWith("'") && v.length > 1)) {
    return v.slice(1, -1).replace(/\\"/g, '"');
  }
  return v;
}
function parseFrontMatter(raw, where) {
  const text = raw.replace(/^﻿/, '').replace(/\r\n?/g, '\n');
  const m = text.match(/^---\n([\s\S]*?)\n---[ \t]*(?:\n|$)/);
  if (!m) { fail(where, '맨 위에 --- 로 둘러싼 머리말(제목·날짜·분야)이 없습니다. content/_template/index.md를 복사해 시작하세요.'); return null; }
  const data = {};
  const lines = m[1].split('\n');
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const kv = line.match(/^([A-Za-z][A-Za-z0-9]*)\s*:\s*(.*)$/);
    if (!kv) { fail(where, `머리말 ${i + 2}번째 줄을 읽을 수 없습니다: "${line}"  (형식: 이름: 값)`); continue; }
    const [, key, rest] = kv;
    if (!KEYS.has(key)) { fail(where, `알 수 없는 머리말 항목 "${key}" 입니다. (사용 가능: ${[...KEYS].join(', ')})`); continue; }
    if (key === 'tags') {
      let list;
      if (rest.trim().startsWith('[')) {
        const inner = rest.trim().replace(/^\[/, '').replace(/\]$/, '');
        list = inner.split(',').map(parseScalar);
      } else if (rest.trim() === '') {
        list = [];
        while (i + 1 < lines.length && /^\s*-\s+/.test(lines[i + 1])) list.push(parseScalar(lines[++i].replace(/^\s*-\s+/, '')));
      } else list = rest.split(',').map(parseScalar);
      data.tags = list.map(t => t.replace(/^#/, '').trim()).filter(Boolean);
    } else data[key] = parseScalar(rest);
  }
  return { data, body: text.slice(m[0].length) };
}
const isTrue = v => v === true || /^(true|yes|y|1)$/i.test(String(v ?? '').trim());

function safeLink(href) {
  const h = String(href ?? '').trim();
  if (!h) return null;
  if (h.startsWith('#')) return h;
  try {
    const u = new URL(h, 'https://base.invalid/dir/');
    if (['http:', 'https:', 'mailto:'].includes(u.protocol)) return h;
  } catch { /* 아래에서 null */ }
  return null;
}
const isExternal = h => /^https?:\/\//i.test(h);

function slugify(text, seen) {
  let base = text.toLowerCase().replace(/<[^>]*>/g, '').trim().replace(/[^\p{L}\p{N}\s_-]/gu, '').replace(/\s+/g, '-').replace(/^-+|-+$/g, '') || 'section';
  let id = base, n = 2;
  while (seen.has(id)) id = `${base}-${n++}`;
  seen.add(id);
  return id;
}

function render(body, ctx) {
  const toc = [];
  const seen = new Set();
  const images = [];
  const md = new Marked({ gfm: true, breaks: false });
  md.use({
    renderer: {
      html(token) { return esc(token.text); }, // 원시 HTML은 실행하지 않고 글자 그대로 보여 준다
      heading(token) {
        const inner = this.parser.parseInline(token.tokens);
        const level = token.depth <= 2 ? 2 : token.depth === 3 ? 3 : 4;
        const plain = token.text.replace(/[*_`~]/g, '').replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').trim();
        const id = slugify(plain, seen);
        if (level <= 3) toc.push({ level, id, text: plain });
        return `<h${level} id="${esc(id)}">${inner}</h${level}>\n`;
      },
      code(token) {
        const lang = (token.lang || '').match(/^[A-Za-z0-9_+-]+/)?.[0];
        return `<pre><code${lang ? ` class="language-${lang}"` : ''}>${esc(token.text)}</code></pre>\n`;
      },
      link(token) {
        const inner = this.parser.parseInline(token.tokens);
        const href = safeLink(token.href);
        if (href === null) { warnings.push(`${ctx.where}: 허용되지 않는 링크 주소를 글자로만 남겼습니다: ${token.href}`); return inner; }
        const title = token.title ? ` title="${esc(token.title)}"` : '';
        const ext = isExternal(href) ? ' target="_blank" rel="noopener noreferrer"' : '';
        return `<a href="${esc(href)}"${title}${ext}>${inner}</a>`;
      },
      image(token) {
        const src = String(token.href ?? '').trim();
        let out;
        if (isExternal(src)) out = src;
        else {
          let local = src;
          try { local = decodeURI(src); } catch { /* 그대로 */ }
          local = local.replace(/^\.\//, '');
          if (!local || /^[a-z][a-z0-9+.-]*:/i.test(local) || local.startsWith('/') || local.split('/').includes('..')) {
            fail(ctx.where, `이미지 주소를 쓸 수 없습니다: ${src}\n    → 글 폴더 안의 파일 이름(예: 사진.png)이나 https:// 주소만 사용할 수 있습니다.`);
            return '';
          }
          if (!fs.existsSync(path.join(ctx.dir, local))) {
            fail(ctx.where, `본문에 쓴 이미지 파일이 글 폴더에 없습니다: ${local}\n    → 이미지를 이 글의 폴더에 함께 올렸는지, 파일 이름의 대소문자까지 같은지 확인하세요.`);
            return '';
          }
          out = local.split('/').map(encodeURIComponent).join('/');
        }
        images.push({ src: out, external: isExternal(src) });
        const title = token.title ? ` title="${esc(token.title)}"` : '';
        return `<img src="${esc(out)}" alt="${esc(token.text || '')}"${title} loading="lazy" decoding="async">`;
      },
    },
  });
  const html = md.parse(body);
  return { html, toc, images };
}

function plainText(html) {
  return html.replace(/<pre[\s\S]*?<\/pre>/g, m => m).replace(/<[^>]+>/g, ' ')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ').trim();
}

function loadPosts() {
  const base = path.join(ROOT, 'content', 'posts');
  if (!fs.existsSync(base)) return [];
  const posts = [];
  for (const ent of fs.readdirSync(base, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!ent.isDirectory() || ent.name.startsWith('_') || ent.name.startsWith('.')) continue;
    const slug = ent.name;
    const dir = path.join(base, slug);
    const file = path.join(dir, 'index.md');
    const where = rel(file);
    if (!/^[a-z0-9][a-z0-9_-]*$/.test(slug)) { fail(rel(dir), `폴더 이름 "${slug}"은 영어 소문자·숫자·하이픈(-)·밑줄(_)만 쓸 수 있습니다. 예: http-headers-compare`); continue; }
    if (!fs.existsSync(file)) { fail(rel(dir), '폴더 안에 index.md 파일이 없습니다. (파일 이름은 반드시 index.md)'); continue; }
    const parsed = parseFrontMatter(read(file), where);
    if (!parsed) continue;
    const { data, body } = parsed;
    if (isTrue(data.draft)) continue;
    const before = errors.length;
    if (!data.title) fail(where, '머리말에 title(제목)이 없습니다.');
    else if (data.title.length > 120) fail(where, 'title이 너무 깁니다(120자 이하).');
    if (!data.date) fail(where, '머리말에 date(날짜)가 없습니다. 형식: 2026-11-12');
    else {
      const d = new Date(data.date + 'T00:00:00Z');
      if (!/^\d{4}-\d{2}-\d{2}$/.test(data.date) || Number.isNaN(d.getTime()) || d.toISOString().slice(0, 10) !== data.date) fail(where, `date "${data.date}"를 읽을 수 없습니다. 실제 있는 날짜를 2026-11-12 형식으로 적어 주세요.`);
    }
    if (!data.category) fail(where, `머리말에 category(분야)가 없습니다. 사용 가능: ${CATEGORIES.map(c => c.key).join(', ')}`);
    else if (!CAT.has(data.category)) fail(where, `category "${data.category}"는 없는 분야입니다. 사용 가능: ${CATEGORIES.map(c => c.key).join(', ')}`);
    if ((data.tags?.length ?? 0) > 8) fail(where, '태그는 8개 이하로 적어 주세요.');
    if (data.readingTime && !/^\d{1,3}$/.test(data.readingTime)) fail(where, 'readingTime은 분 단위 숫자만 적어 주세요. 예: 5');
    if (!body.trim()) fail(where, '본문이 비어 있습니다.');
    if (errors.length > before) continue;

    const noFence = body.replace(/^(```|~~~)[\s\S]*?^\1/gm, '');
    for (const m of noFence.matchAll(/!\[[^\]]*\]\(([^)<>\n]*\s[^)\n]*)\)/g)) {
      fail(where, `이미지 주소에 띄어쓰기가 있어 이미지로 인식되지 않습니다: ${m[1]}\n    → 파일 이름의 띄어쓰기를 -로 바꾸거나, 주소를 <>로 감싸세요.  예: ![설명](<화면 캡처.png>)`);
    }
    if (errors.length > before) continue;
    const ctx = { where, dir };
    const { html, toc, images } = render(body, ctx);
    const text = plainText(html);
    let thumb = null;
    if (data.thumbnail && data.thumbnail !== 'none') {
      const t = data.thumbnail.trim();
      if (isExternal(t)) thumb = { src: t, external: true };
      else if (t.includes('/') || t.includes('..') || !fs.existsSync(path.join(dir, t))) fail(where, `thumbnail "${t}" 파일을 글 폴더에서 찾을 수 없습니다.`);
      else thumb = { src: encodeURIComponent(t), external: false };
    } else if (data.thumbnail !== 'none' && images[0]) thumb = images[0];
    const summary = (data.summary || text.slice(0, 90)).trim();
    posts.push({
      slug, dir, where,
      title: data.title.trim(), date: data.date, category: data.category,
      summary, tags: data.tags ?? [], example: isTrue(data.example),
      minutes: data.readingTime ? Number(data.readingTime) : Math.max(1, Math.round(text.replace(/\s/g, '').length / 600)),
      html, toc, thumb, text,
    });
  }
  posts.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug.localeCompare(b.slug)));
  return posts;
}


