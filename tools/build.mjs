function replaceBetween(html, name, inner, where) {
  const re = new RegExp(`(<!--build:${name}-->)[\\s\\S]*?(<!--/build:${name}-->)`);
  if (!re.test(html)) { fail(where, `<!--build:${name}--> ... <!--/build:${name}--> 표시를 찾을 수 없습니다. 지우지 마세요.`); return html; }
  return html.replace(re, (_, a, b) => `${a}${inner}${b}`);
}

