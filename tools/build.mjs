// content/news/*.json 한 파일 = 뉴스 한 건 → assets/security-news.js
function loadNews() {
  const dir = path.join(ROOT, 'content', 'news');
  if (!fs.existsSync(dir)) return [];
  const items = [];
  const validDay = v => typeof v === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(v) && !Number.isNaN(Date.parse(v + 'T00:00:00Z')) && new Date(v + 'T00:00:00Z').toISOString().slice(0, 10) === v;
  for (const name of fs.readdirSync(dir).filter(n => n.endsWith('.json')).sort()) {
    const where = `content/news/${name}`;
    let data;
    try { data = JSON.parse(read(path.join(dir, name))); } catch (e) { fail(where, `JSON을 읽을 수 없습니다: ${e.message}`); continue; }
    if (!data || typeof data !== 'object' || Array.isArray(data)) { fail(where, '객체({ ... }) 하나여야 합니다.'); continue; }
    const before = errors.length;
    for (const k of Object.keys(data)) if (!NEWS_KEYS.has(k)) fail(where, `알 수 없는 항목 "${k}" 입니다. (사용 가능: ${[...NEWS_KEYS].join(', ')})`);
    if (!validDay(data.date)) fail(where, 'date는 실제 있는 날짜를 2026-11-12 형식으로 적어야 합니다.');
    if (data.publishedDate !== undefined && !validDay(data.publishedDate)) fail(where, 'publishedDate는 2026-11-12 형식이어야 합니다.');
    for (const k of ['title', 'source', 'note']) if (typeof data[k] !== 'string' || !data[k].trim()) fail(where, `${k}가 비어 있습니다.`);
    try {
      const u = new URL(data.url);
      if (!['http:', 'https:'].includes(u.protocol) || u.username || u.password) throw new Error('scheme');
    } catch { fail(where, 'url은 http:// 또는 https:// 로 시작하는 주소여야 합니다.'); }
    if (errors.length > before) continue;
    items.push({ ...data, _name: name });
  }
  items.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a._name.localeCompare(b._name)));
  return items.map(({ _name, ...rest }) => rest);
}
