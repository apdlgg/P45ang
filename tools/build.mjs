function listHtml(dir, out = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    if (['.git', '.github', 'node_modules', 'content', 'tools'].includes(ent.name)) continue;
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) listHtml(p, out);
    else if (ent.name.endsWith('.html')) out.push(p);
  }
  return out;
}
function stampVersions() {
  const hashes = new Map();
  const hashOf = name => {
    if (!hashes.has(name)) {
      const file = path.join(ROOT, 'assets', name);
      hashes.set(name, fs.existsSync(file) ? crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex').slice(0, 12) : null);
    }
    return hashes.get(name);
  };
  for (const file of listHtml(ROOT)) {
    const html = read(file);
    const next = html.replace(/(assets\/([\w.-]+\.(?:css|js)))\?v=[0-9a-f]+/g, (m, url, name) => (hashOf(name) ? `${url}?v=${hashOf(name)}` : m));
    write(file, next);
  }
}

